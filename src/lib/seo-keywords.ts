/** Flattened, de-duplicated list for one or more clusters, in one language. */
export function keywordsFor(locale: Locale, ...clusters: KeywordCluster[]): string[] {
  return [...new Set(clusters.flatMap((cluster) => seoKeywords[locale][cluster]))];
}
